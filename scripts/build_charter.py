#!/usr/bin/env python3
"""Agent charter: one short, imperative document every build session loads, generated from its sources.

The rules live where they are owned and approved; this script assembles them so a builder (and a human) can read
everything in one place. Never hand-edit the output; change the source and rebuild.

  Section              Source
  Stack and structure  .ai/standards/coding-standards.md (project-specific table) + Approved ADRs
  Conventions          .ai/standards/coding-standards.md (defaults + remaining project-specific rows) + Approved domain glossary
  Forbidden actions    CLAUDE.md non-negotiable rules + .claude/settings.json deny list + .claude/hooks
  Definition of done   Approved definition-of-done artifact (Phase 5); reference default until then
  Commands             .ai/standards/automated-gates.md (made runnable by Task 0)
  Learned rules        Approved learned rules (docs/logs/learned-rules/)

Usage:
  python3 scripts/build_charter.py build   # write .ai/standards/agent-charter.md
  python3 scripts/build_charter.py check   # CI: the charter matches its sources exactly
"""
import ast
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sdlc_lib import DOCS, ROOT, read_artifact, sections, strip_comments  # noqa: E402

OUT = ROOT / ".ai" / "standards" / "agent-charter.md"
STD = ROOT / ".ai" / "standards" / "coding-standards.md"
GATES = ROOT / ".ai" / "standards" / "automated-gates.md"
CLAUDE = ROOT / "CLAUDE.md"
SETTINGS = ROOT / ".claude" / "settings.json"
HOOKS = ROOT / ".claude" / "hooks"
STACK_ROWS = ("Backend language and framework", "Frontend language and framework", "Database", "Folder layout")
NOT_SET = re.compile(r"<(?:to be )?set in Phase 4[^>]*>")


def read(p):
    return p.read_text(encoding="utf-8").replace("\r\n", "\n") if p.exists() else ""


def md_sections(text):
    out, cur, buf = {}, None, []
    for ln in text.splitlines():
        if ln.startswith("## "):
            if cur:
                out[cur] = "\n".join(buf).strip()
            cur, buf = ln[3:].strip(), []
        elif cur:
            buf.append(ln)
    if cur:
        out[cur] = "\n".join(buf).strip()
    return out


def table(text):
    rows = []
    for ln in text.splitlines():
        if ln.strip().startswith("|"):
            c = [x.strip() for x in ln.strip().strip("|").split("|")]
            if not all(re.fullmatch(r":?-{3,}:?", x) for x in c if x):
                rows.append(c)
    return rows[1:]


def val(v):
    return "not set yet (Phase 4)" if NOT_SET.search(v) or not v else v


def artifacts(template, status="Approved"):
    out = []
    for p in sorted(DOCS.rglob("*.md")):
        try:
            fm, body, _ = read_artifact(p)
        except Exception:
            continue
        if fm and fm.get("template") == template and fm.get("status") == status:
            out.append((fm, {h: strip_comments(c) for h, c in sections(body)}))
    return out


def first_line(txt):
    return next((ln.strip().lstrip("-* ").strip() for ln in txt.splitlines() if ln.strip()), "")


def render():
    std = md_sections(read(STD))
    proj = {r[0]: r[1] for r in table(std.get("Project-specific (filled in Phase 4)", "")) if len(r) >= 2}
    L = ["# Agent Charter", "",
         "Generated by `python3 scripts/build_charter.py build`. Do not edit: change the source named in each section, then rebuild "
         "(CI fails if this file and its sources differ). Every builder and the AI reviewer load this file.", ""]

    # 1. Stack and structure
    L += ["## Stack and structure", ""]
    for k in STACK_ROWS:
        L.append(f"- **{k}:** {val(proj.get(k, ''))}")
    adrs = artifacts("adr")
    if adrs:
        L += ["", "Architecture decisions to follow (Approved ADRs):", ""]
        for fm, s in adrs:
            L.append(f"- {fm['id']} v{fm.get('version')}: {fm.get('title')}. {first_line(s.get('Decision', ''))}".rstrip())
    L += ["", "Source: `.ai/standards/coding-standards.md`, Approved ADRs.", ""]

    # 2. Conventions
    L += ["## Conventions", ""]
    L += [ln for ln in std.get("Defaults for all code", "").splitlines() if ln.startswith("- ")]
    for k, v in proj.items():
        if k not in STACK_ROWS:
            L.append(f"- **{k}:** {val(v)}")
    gl = artifacts("domain-glossary")
    if gl:
        gfm, gs = gl[-1]
        L += ["", f"Domain terms: name things (code, API fields, tables, UI text) with these terms, never the avoided ones ({gfm['id']} v{gfm.get('version')}):", ""]
        for ln in gs.get("Terms", "").splitlines():
            c = [x.strip() for x in ln.strip().strip("|").split("|")] if ln.strip().startswith("|") else []
            if len(c) >= 3 and c[0] and c[0].lower() != "term" and not re.fullmatch(r":?-{3,}:?", c[0]):
                avoid = c[2] if c[2] and c[2] != "-" else "nothing listed"
                L.append(f"- **{c[0]}**: {c[1]} Avoid: {avoid}.")
    L += ["", "Source: `.ai/standards/coding-standards.md`" + (", Approved domain glossary." if gl else "."), ""]

    # 3. Forbidden actions
    L += ["## Forbidden actions", ""]
    rules = md_sections(read(CLAUDE)).get("Non-negotiable rules", "")
    L += [ln for ln in rules.splitlines() if re.match(r"\d+\. ", ln)]
    deny = json.loads(read(SETTINGS) or "{}").get("permissions", {}).get("deny", [])
    if deny:
        L += ["", "Blocked by settings (the tool call is refused):", ""]
        groups = {}
        for d in deny:
            m = re.match(r"(\w+)\((.*)\)$", d)
            if m:
                groups.setdefault(m.group(1), []).append(m.group(2))
        labels = {"Read": "Never read", "Edit": "Never edit", "Write": "Never write", "Bash": "Never run"}
        for tool in ("Read", "Edit", "Write", "Bash"):
            if tool in groups:
                L.append(f"- {labels[tool]}: " + ", ".join(f"`{x}`" for x in groups[tool]))
    hooks = sorted(HOOKS.glob("*.py")) if HOOKS.exists() else []
    if hooks:
        L += ["", "Blocked by hooks (checked before every matching tool call):", ""]
        for h in hooks:
            doc = ast.get_docstring(ast.parse(read(h))) or ""
            L.append(f"- `{h.name}`: {' '.join(doc.split(chr(10) + chr(10))[0].split())}")
    L += ["", "Source: `CLAUDE.md`, `.claude/settings.json`, `.claude/hooks/`.", ""]

    # 4. Definition of done
    L += ["## Definition of done", ""]
    dods = artifacts("definition-of-done")
    if dods:
        fm, s = dods[-1]
        L += [ln for ln in s.get("Checklist", "").splitlines() if ln.strip()]
        L += ["", f"Source: {fm['id']} v{fm.get('version')} (Approved).", ""]
    else:
        L += ["- [ ] Approved tests pass; all automated gates clean",
              "- [ ] Change summary written (Requirements Covered, Known Gaps, Deviations From Plan, Blockers)",
              "- [ ] Traceability matrix updated",
              "", "Source: default until the Definition of Done is Approved in Phase 5.", ""]

    # 5. Commands
    L += ["## Commands", "", "| Gate | Command | Required |", "| --- | --- | --- |"]
    for r in table(read(GATES)):
        if len(r) >= 3:
            cmd = "not set yet (Phase 4; made runnable by Task 0)" if NOT_SET.search(r[1]) else r[1]
            L.append(f"| {r[0]} | {cmd} | {r[2]} |")
    L += ["", "Source: `.ai/standards/automated-gates.md`.", ""]

    # 6. Learned rules
    L += ["## Learned rules", ""]
    lrns = artifacts("learned-rule")
    if lrns:
        for fm, s in lrns:
            rule = " ".join(s.get("Rule", "").split())
            L.append(f"- **{fm['id']}** ({first_line(s.get('Category', '')).strip('`')}; {' '.join(s.get('Applies To', '').split())}): {rule}")
    else:
        L.append("No learned rules yet.")
    L += ["", "Source: Approved learned rules (`docs/logs/learned-rules/`).", ""]
    return "\n".join(L).rstrip() + "\n"


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("build", "check"):
        print(__doc__)
        return 2
    want = render()
    if sys.argv[1] == "build":
        OUT.write_bytes(want.encode("utf-8"))
        print(f"Wrote {OUT.relative_to(ROOT).as_posix()} ({len(want.splitlines())} lines).")
        return 0
    have = OUT.read_bytes().decode("utf-8").replace("\r\n", "\n") if OUT.exists() else ""
    if have != want:
        print(f"FAIL  {OUT.relative_to(ROOT).as_posix()} does not match its sources. Run 'python3 scripts/build_charter.py build'; "
              "never hand-edit the charter.")
        return 1
    print("Agent charter matches its sources.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
