#!/usr/bin/env python3
"""Feedback and incident log (D30): one generated view of what came in from production and what happened to it.

Reads Phase 9 artifacts under docs/: incident reports (INC), post-mortems (PMT), feedback summaries (FBK),
production defect reports (DEF under docs/09-operate/), and improvement backlog items (IMP). An item's outcome is
every improvement backlog item, defect report, spec change record, or feature plan (Fix feature) that mentions its
ID, plus every decision log row whose Context names it (for example a 'no action' decision by the product owner).

Usage:
  python3 scripts/feedback_log.py build          # regenerate docs/logs/feedback-incident-log.md
  python3 scripts/feedback_log.py check          # CI: the log matches the artifacts (run build if not)
  python3 scripts/feedback_log.py check --gate   # Phase 9 gate: also every incident, feedback summary, and production
                                                 # defect that is not Rejected has an outcome, and every improvement
                                                 # backlog item is Approved or Rejected
Exit code 1 on any violation (build: never).
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from sdlc_lib import DOCS, ID_TOKEN, ROOT, read_artifact, sections, strip_comments  # noqa: E402

LOG = DOCS / "logs" / "feedback-incident-log.md"
DECISION_LOG = DOCS / "logs" / "decision-log.md"
APPROVAL_LOG = DOCS / "logs" / "approval-log.md"
OPERATE = DOCS / "09-operate"
INCOMING = {"incident-report": "Incident", "post-mortem": "Post-mortem", "feedback-summary": "Feedback",
            "defect-report": "Production defect"}
NEEDS_OUTCOME = {"incident-report", "feedback-summary", "defect-report"}
OUTCOME_TEMPLATES = {"improvement-backlog-item", "defect-report", "spec-change", "feature-plan"}
DECIDED = {"Approved": "Enters next cycle", "Rejected": "Not taken"}


def load():
    arts = []
    for p in sorted(DOCS.rglob("*.md")):
        try:
            fm, body, _ = read_artifact(p)
        except Exception:
            continue
        if fm and fm.get("id") and fm.get("template"):
            arts.append({"id": fm["id"], "template": fm["template"], "status": fm.get("status", ""),
                         "title": fm.get("title", ""), "date": fm.get("date", ""), "path": p, "body": body})
    return arts


def is_incoming(a):
    if a["template"] == "defect-report":
        return OPERATE in a["path"].parents  # Phase 7 defects are tracked by traceability.py check --phase 7
    return a["template"] in INCOMING


def section(a, name):
    return strip_comments(dict(sections(a["body"])).get(name, "")).strip()


def mentioned(a):
    text = strip_comments("\n".join(c for h, c in sections(a["body"]) if h != "Approval Record"))
    return set(ID_TOKEN.findall(text)) - {a["id"]}


def cell(s, n=60):
    s = next((ln.strip() for ln in str(s).splitlines() if ln.strip()), "-")
    return s.replace("|", "/")[:n]


def table_rows(path, min_cells):
    if not path.exists():
        return []
    rows = ([c.strip() for c in ln.strip().strip("|").split("|")] for ln in path.read_text(encoding="utf-8").splitlines())
    return [r for r in rows if len(r) >= min_cells]


def decisions():
    """artifact id -> {DEC-NNN} for decision log rows whose Context names it."""
    out = {}
    for r in table_rows(DECISION_LOG, 7):
        if re.fullmatch(r"DEC-\d{3}", r[0]):
            for i in ID_TOKEN.findall(r[6]):
                out.setdefault(i, set()).add(r[0])
    return out


def last_approvals():
    """artifact id -> (timestamp, approver) of its newest approval log row."""
    return {r[1]: (r[0], r[4]) for r in table_rows(APPROVAL_LOG, 5) if ID_TOKEN.fullmatch(r[1])}


def render(arts):
    by_id = {a["id"]: a for a in arts}
    ments = {a["id"]: mentioned(a) for a in arts}
    decs, appr = decisions(), last_approvals()
    incoming = sorted((a for a in arts if is_incoming(a)), key=lambda a: a["id"])
    imps = sorted((a for a in arts if a["template"] == "improvement-backlog-item"), key=lambda a: a["id"])
    problems = []
    lines = ["# Feedback and Incident Log", "",
             "Generated by `python3 scripts/feedback_log.py build` from the Phase 9 incident reports, post-mortems, feedback "
             "summaries, production defect reports, and improvement backlog items. Do not edit by hand. An item showing "
             "'Pending triage' needs an outcome: an improvement backlog item, a defect report, a spec change record, or a "
             "named 'no action' decision (`python3 scripts/log_decision.py add --context <ID>`).", "",
             "## Incoming", "",
             "| ID | Type | Title | Date | Status | Led to |",
             "| --- | --- | --- | --- | --- | --- |"]
    for a in incoming:
        led = sorted({o["id"] for o in arts if o["template"] in OUTCOME_TEMPLATES and a["id"] in ments[o["id"]]}
                     | decs.get(a["id"], set()))
        lines.append(f"| {a['id']} | {INCOMING[a['template']]} | {cell(a['title'])} | {a['date']} | {a['status']} | "
                     f"{', '.join(led) or 'Pending triage'} |")
        if not led and a["template"] in NEEDS_OUTCOME and a["status"] != "Rejected":
            problems.append(f"{a['id']}: no outcome yet (improvement backlog item, defect report, SCR, or a 'no action' DEC-NNN)")
    lines += ["", "## Next-cycle decisions", "",
              "The product owner decides each improvement backlog item with `/approve`: Approve = it enters the next cycle "
              "at its target phase; Reject = not taken, with the reason in the approval log.", "",
              "| IMP | Title | Evidence | Target phase | Priority | Decision | Decided by | Decided (UTC) |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]
    for a in imps:
        evidence = sorted(i for i in ments[a["id"]] if i in by_id and is_incoming(by_id[i]))
        ts, who = appr.get(a["id"], ("-", "-")) if a["status"] in DECIDED else ("-", "-")
        lines.append(f"| {a['id']} | {cell(a['title'])} | {', '.join(evidence) or '-'} | {cell(section(a, 'Target Phase'), 30)} | "
                     f"{cell(section(a, 'Priority'), 30)} | {DECIDED.get(a['status'], 'Awaiting decision')} | {who} | {ts} |")
        if a["status"] not in DECIDED:
            problems.append(f"{a['id']}: improvement backlog item is {a['status']}; the product owner approves or rejects it")
    return "\n".join(lines) + "\n", problems, len(incoming), len(imps)


def cmd_build():
    text, _, n_in, n_imp = render(load())
    LOG.write_text(text, encoding="utf-8")
    print(f"Wrote {LOG.relative_to(ROOT).as_posix()} ({n_in} incoming item(s), {n_imp} improvement item(s)).")
    return 0


def cmd_check(gate):
    text, problems, n_in, n_imp = render(load())
    current = LOG.read_text(encoding="utf-8") if LOG.exists() else ""
    out = [] if current == text else ["docs/logs/feedback-incident-log.md is out of date: run python3 scripts/feedback_log.py build"]
    if gate:
        out += problems
    for p in out:
        print(f"FAIL  {p}")
    print(f"Feedback and incident log: {n_in} incoming, {n_imp} improvement item(s), {len(out)} problem(s)"
          f"{' (Phase 9 gate)' if gate else ''}.")
    return 1 if out else 0


def main():
    a = sys.argv[1:]
    if not a or a[0] not in ("build", "check"):
        print(__doc__)
        return 2
    return cmd_build() if a[0] == "build" else cmd_check("--gate" in a[1:])


if __name__ == "__main__":
    sys.exit(main())